/**
 * Regenerate the translation seed migration from the live database.
 *
 * This exists because of a real drift: every UI string added after Phase 1 was
 * applied straight to the remote project and never written to a migration
 * file. The repo held 11 migrations against 43 applied, and a fresh Supabase
 * project checked out from this repo would have come up with the full schema
 * and almost no UI strings — rendering bare message keys like
 * `action.evacuate_now` on every screen.
 *
 * The REPO is the source of truth from here on: `scripts/check-translations.mjs`
 * fails the build if a key used in the app is missing from the migrations. This
 * script is the reconciliation tool for when drift has already happened — run
 * it, review the diff, commit the file.
 *
 * Run:  node scripts/dump-translations.mjs
 */

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(fileURLToPath(new URL(".", import.meta.url)), "..");
const OUT = join(ROOT, "supabase/migrations/0012_translations_complete.sql");

const env = Object.fromEntries(
  readFileSync(join(ROOT, ".env.local"), "utf8")
    .split("\n")
    .filter((l) => l.trim() && !l.trim().startsWith("#"))
    .map((l) => {
      const i = l.indexOf("=");
      return [l.slice(0, i).trim(), l.slice(i + 1).trim()];
    }),
);

const URL_ = env.NEXT_PUBLIC_SUPABASE_URL;
const KEY = env.NEXT_PUBLIC_SUPABASE_ANON_KEY;

/* Translations are readable `to authenticated`, so this needs a session — but
   only an anonymous one. No service-role key is involved. */
const session = await (
  await fetch(`${URL_}/auth/v1/signup`, {
    method: "POST",
    headers: { apikey: KEY, "Content-Type": "application/json" },
    body: "{}",
  })
).json();

const rows = [];
const PAGE = 500;
for (let from = 0; ; from += PAGE) {
  const res = await fetch(
    `${URL_}/rest/v1/translations?select=message_key,language,text&order=message_key.asc,language.asc`,
    {
      headers: {
        apikey: KEY,
        Authorization: `Bearer ${session.access_token}`,
        Range: `${from}-${from + PAGE - 1}`,
      },
    },
  );
  const page = await res.json();
  if (!Array.isArray(page)) {
    console.error("unexpected response:", JSON.stringify(page).slice(0, 200));
    process.exitCode = 1;
    break;
  }
  rows.push(...page);
  if (page.length < PAGE) break;
}

/** Postgres string literal: the only escape that matters is the quote itself. */
const lit = (s) => `'${String(s).replace(/'/g, "''")}'`;

const values = rows
  .map((r) => `  (${lit(r.message_key)}, ${lit(r.language)}, ${lit(r.text)})`)
  .join(",\n");

const keys = new Set(rows.map((r) => r.message_key));

const sql = `-- Complete UI translation seed (FR-3.1..3.5).
--
-- Generated by scripts/dump-translations.mjs. Do not hand-edit: add strings in
-- a NEW migration, then regenerate this file if the two ever drift again.
--
-- Why this file exists: every string added after Phase 1 was applied directly
-- to the remote project and never committed, so the repo could not rebuild its
-- own database. A fresh project would have started with the schema and no UI
-- strings, rendering bare message keys on every screen.
--
-- Idempotent, and safe to run over an already-seeded database: earlier
-- migrations insert a subset of these same keys, and the upsert reconciles
-- them to this file's text rather than failing on the conflict.
--
-- ${keys.size} keys, ${rows.length} rows, ${new Set(rows.map((r) => r.language)).size} languages.
--
-- One deliberate absence to preserve: Cebuano for \`action.stay_inside\` and
-- \`headline.stay_inside\`. The FR-3.5 fallback path needs data that actually
-- exercises it, and the rarest signal level is the one a barangay is least
-- likely to have finished translating. If a future dump shows those keys with
-- three languages, the gap was filled by accident and the fallback is no
-- longer covered.

insert into public.translations (message_key, language, text) values
${values}
on conflict (message_key, language) do update set text = excluded.text;
`;

writeFileSync(OUT, sql);
console.log(`${rows.length} rows, ${keys.size} keys -> ${OUT.replace(ROOT, ".")}`);
