/**
 * Writes the machine translations in translations/machine/<code>.json into a
 * migration.
 *
 * The JSON files are the source a native speaker edits: one file per language,
 * one key per UI string, English beside nothing — the English and Tagalog are
 * in the earlier migrations. Correcting a language is: edit its file, run this
 * with a NEW migration name, apply that migration. Applied migrations are never
 * edited.
 *
 * Every file is checked before anything is written: every key the English has,
 * no key it lacks, the {n} placeholder kept exactly as often as the English uses
 * it. A string that drops {n} would show "SIGNAL NO." with no number during a
 * storm, and a missing key would silently fall back to Tagalog.
 *
 * Filipino (fil) is written from the Tagalog strings already in the database
 * migrations, not machine-translated: standard Filipino is Tagalog-based, and
 * the reviewed Tagalog is better than any translation of it.
 *
 * Run:  node scripts/generate-translations.mjs supabase/migrations/0030_machine_translations.sql
 */

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { MACHINE_TRANSLATED } from "../src/lib/i18n.ts";

const ROOT = join(fileURLToPath(new URL(".", import.meta.url)), "..");
const DIR = join(ROOT, "translations/machine");
const MIGRATIONS = join(ROOT, "supabase/migrations");
const out = process.argv[2];
if (!out) {
  console.error("Usage: node scripts/generate-translations.mjs <migration path>");
  process.exit(1);
}

/* Every en/tl string already in the migrations, latest wins. */
const base = {};
for (const file of readdirSync(MIGRATIONS).sort()) {
  const sql = readFileSync(join(MIGRATIONS, file), "utf8");
  for (const m of sql.matchAll(
    /\(\s*'([a-z_]+\.[a-z0-9_]+)'\s*,\s*'(en|tl|ceb)'\s*,\s*'((?:[^']|'')*)'\s*\)/g,
  )) {
    (base[m[1]] ??= {})[m[2]] = m[3].replace(/''/g, "'");
  }
}

/* The two strings this change adds, in the reviewed languages. */
const ADDED = {
  "ui.lang_machine": {
    en: "Machine-translated — not yet checked by a native speaker",
    tl: "Isinalin ng makina — hindi pa nasusuri ng katutubong nagsasalita",
    ceb: "Gihubad sa makina — wala pa masusi sa lumad nga mamumulong",
  },
  "ui.machine_note": {
    en: "Machine-translated. If anything is unclear, follow the barangay's announcement.",
    tl: "Isinalin ng makina. Kung may hindi malinaw, sundin ang anunsyo ng barangay.",
    ceb: "Gihubad sa makina. Kon naay dili klaro, sunda ang pahibalo sa barangay.",
  },
};
for (const [key, texts] of Object.entries(ADDED)) base[key] = { ...base[key], ...texts };

const keys = Object.keys(base).filter((k) => base[k].en).sort();
const count = (s) => (s.match(/\{n\}/g) ?? []).length;

// Staff-only screens: a machine language may leave these out and fall back to Tagalog.
const optional = (key) => /^(roles|ci|evac)\./.test(key);

const problems = [];
const files = readdirSync(DIR).filter((f) => f.endsWith(".json")).sort();
const languages = {};
for (const file of files) {
  const code = file.replace(/\.json$/, "");
  if (!MACHINE_TRANSLATED.has(code)) problems.push(`${code}: not listed in MACHINE_TRANSLATED`);
  const strings = JSON.parse(readFileSync(join(DIR, file), "utf8"));
  for (const key of keys) {
    const text = strings[key];
    if (text === undefined && optional(key)) continue;
    if (typeof text !== "string" || !text.trim()) problems.push(`${code}: missing ${key}`);
    else if (count(text) !== count(base[key].en)) problems.push(`${code}: {n} in ${key}`);
  }
  for (const key of Object.keys(strings)) {
    if (!keys.includes(key)) problems.push(`${code}: unknown key ${key}`);
  }
  languages[code] = strings;
}
for (const code of MACHINE_TRANSLATED) {
  if (!languages[code]) problems.push(`${code}: listed in MACHINE_TRANSLATED but has no file`);
}
if (problems.length) {
  console.error(problems.join("\n"));
  process.exit(1);
}

const q = (s) => `'${s.replace(/'/g, "''")}'`;
const rows = [];
for (const key of Object.keys(ADDED)) {
  for (const [lang, text] of Object.entries(ADDED[key])) rows.push(`(${q(key)}, ${q(lang)}, ${q(text)})`);
}
for (const key of keys) rows.push(`(${q(key)}, 'fil', ${q(base[key].tl ?? base[key].en)})`);
for (const [code, strings] of Object.entries(languages)) {
  for (const key of keys) {
    if (strings[key] !== undefined) rows.push(`(${q(key)}, ${q(code)}, ${q(strings[key])})`);
  }
}

const sql = `-- Every language in the picker, translated.
--
-- GENERATED by scripts/generate-translations.mjs from translations/machine/*.json.
-- Do not edit this file; edit the JSON and generate a new migration.
--
-- ${files.length} languages are MACHINE-TRANSLATED and have not been checked by a
-- native speaker: ${Object.keys(languages).join(", ")}.
-- The app labels them as such in the picker and under every instruction
-- (MACHINE_TRANSLATED in src/lib/i18n.ts, ui.lang_machine, ui.machine_note).
-- For the smaller languages few written sources exist, and some of the wording
-- is closer to a regional lingua franca than to the language itself.
--
-- Filipino (fil) is the reviewed Tagalog, copied — not machine-translated.
--
-- ${rows.length} rows.

insert into public.translations (message_key, language, text) values
${rows.join(",\n")}
on conflict (message_key, language) do update set text = excluded.text;
`;
writeFileSync(join(ROOT, out), sql);
console.log(`Wrote ${out}: ${rows.length} rows, ${files.length} machine-translated languages + fil.`);
